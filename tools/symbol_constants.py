"""Generate C++ address constants from a decomp's symbol map.

    symbol_constants.py --images <images.toml> --namespace <ns> --output <dir>
    symbol_constants.py --images <images.toml> --list

`images.toml` lists `[[image]]` tables with `file`, `symbols` (a splat `symbol_addrs` file,
relative to the decomp root, the parent of the toml's directory) and `sections`
(`name`, `start`, `size`, `execute`). Each symbol line is `Name = 0xADDR; // type:func size:0x10`;
`type` (`func`, `label`, `data`) and `size` are the only attributes read.

For each image with a symbol file this writes `<dir>/<stem>_symbols.hpp`, whose constants live in
`<ns>::<stem>`, a `<Name>_size` beside each sized symbol. A file is rewritten only when its text
changes. It refuses a malformed line, a duplicate name or address, an address outside every
section of its image, and code (`func`, `label`) outside an executable section.

`--list` prints `<header>|<symbol file>` per mapped image, for the build to declare.
"""

import argparse
import os
import re
import sys
import tomllib

SYMBOL = re.compile(r"^([A-Za-z_]\w*)\s*=\s*0x([0-9A-Fa-f]+);\s*(?://\s*(.*))?$")
ATTRIBUTE = re.compile(r"^(type|size):(\S+)$")
TYPES = ("func", "label", "data")


class MapError(Exception):
    pass


def parse_symbols(path, label):
    """Yield (line, name, address, type, size) for each symbol in a splat symbol_addrs file."""
    with open(path) as file:
        for number, line in enumerate(file, 1):
            line = line.strip()
            if not line or line.startswith("//"):
                continue
            where = "%s:%d" % (label, number)
            match = SYMBOL.match(line)
            if not match:
                raise MapError("%s: not `Name = 0xADDR; // type:...`" % where)
            kind = None
            size = None
            for word in (match.group(3) or "").split():
                attribute = ATTRIBUTE.match(word)
                if not attribute:
                    raise MapError("%s: unknown attribute %r" % (where, word))
                if attribute.group(1) == "type":
                    if attribute.group(2) not in TYPES:
                        raise MapError("%s: unknown type %r" % (where, attribute.group(2)))
                    kind = attribute.group(2)
                else:
                    size = int(attribute.group(2), 0)
            yield where, match.group(1), int(match.group(2), 16), kind, size


def load_image(root, image):
    """The checked symbols of one image, in file order."""
    path = os.path.join(root, image["symbols"])
    names = set()
    addresses = set()
    symbols = []
    for where, name, address, kind, size in parse_symbols(path, image["symbols"]):
        if name in names:
            raise MapError("%s: %s named twice" % (where, name))
        if address in addresses:
            raise MapError("%s: 0x%08X named twice" % (where, address))
        names.add(name)
        addresses.add(address)
        section = next((s for s in image["sections"]
                        if s["start"] <= address < s["start"] + s["size"]), None)
        if section is None:
            raise MapError("%s: %s 0x%08X is in no section of %s"
                           % (where, name, address, image["file"]))
        if kind in ("func", "label") and not section["execute"]:
            raise MapError("%s: %s is code but 0x%08X is in %s"
                           % (where, name, address, section["name"]))
        symbols.append((name, address, size))
    return symbols


def stem(image):
    return os.path.splitext(os.path.basename(image["symbols"]))[0]


def header(namespace, image, symbols):
    lines = [
        "// Generated by x86port tools/symbol_constants.py from %s. Do not edit." % image["symbols"],
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace %s::%s {" % (namespace, stem(image)),
        "",
    ]
    for name, address, size in symbols:
        lines.append("inline constexpr std::uint32_t %s = 0x%08Xu;" % (name, address))
        if size is not None:
            lines.append("inline constexpr std::uint32_t %s_size = 0x%Xu;" % (name, size))
    lines += ["", "} // namespace %s::%s" % (namespace, stem(image)), ""]
    return "\n".join(lines)


def write_if_changed(path, text):
    if os.path.isfile(path):
        with open(path) as file:
            if file.read() == text:
                return
    with open(path, "w") as file:
        file.write(text)


def mapped_images(images_path):
    root = os.path.dirname(os.path.dirname(os.path.abspath(images_path)))
    with open(images_path, "rb") as file:
        images = tomllib.load(file)["image"]
    return root, [image for image in images if os.path.isfile(os.path.join(root, image["symbols"]))]


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--images", required=True)
    parser.add_argument("--namespace")
    parser.add_argument("--output")
    parser.add_argument("--list", action="store_true")
    args = parser.parse_args(argv)
    root, images = mapped_images(args.images)
    if args.list:
        for image in images:
            print("%s_symbols.hpp|%s" % (stem(image), os.path.join(root, image["symbols"])))
        return 0
    if not args.namespace or not args.output:
        parser.error("--namespace and --output are required unless --list")
    try:
        generated = [(image, load_image(root, image)) for image in images]
    except MapError as error:
        print("symbol_constants: %s" % error, file=sys.stderr)
        return 1
    os.makedirs(args.output, exist_ok=True)
    for image, symbols in generated:
        write_if_changed(os.path.join(args.output, "%s_symbols.hpp" % stem(image)),
                         header(args.namespace, image, symbols))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
